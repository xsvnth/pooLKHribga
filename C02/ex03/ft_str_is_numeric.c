int	ft_str_is_numeric(char *str)
{
	int	i;
	int	alpha;

	i = 0;
	alpha = 1;
	while (str[i] != '\0')
	{
		if (!(str[i] >= '0' && str[i] <= '9'))
		{
			alpha = 0;
		}
		i++;
	}
	return (alpha);
}
