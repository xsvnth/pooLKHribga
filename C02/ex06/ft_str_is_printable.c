int	ft_str_is_printable(char *str)
{
	int	i;
	int	alpha;

	i = 0;
	alpha = 1;
	while (str[i] != '\0')
	{
		if (!(str[i] >= ' ' && str[i] <= '~'))
		{
			alpha = 0;
		}
		i++;
	}
	return (alpha);
}
